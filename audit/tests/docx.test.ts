import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { strFromU8, strToU8, unzipSync, zipSync } from "fflate";
import { describe, expect, it } from "vitest";
import { applyDocumentTranslations, DocxDocumentAdapter, prepareDocument } from "../../src/index.js";
import { init, project } from "../helpers.js";

/**
 * Independent DOCX corpus:
 *  - REF: a real-world, Word-authored template shipped in a third-party plugin cache
 *         (path given by AUDIT_REF_DOCX, skipped if absent).
 *  - LO:  complex.docx generated by LibreOffice from a hand-written FODT containing
 *         header/footer, footnote, endnote, hyperlink, date field, page field, text box,
 *         tracked insertion + deletion, comment, bookmark, table (AUDIT_LO_DOCX).
 *  - Hand-written WordprocessingML for Word-specific constructs (content controls,
 *    HYPERLINK complex fields, smart tags, comment ranges mid-sentence).
 * LibreOffice is used as an independent oracle: it must open the output, and its text
 * export is used to detect untranslated text.
 */
const REF = process.env.AUDIT_REF_DOCX ?? "";
const LO = process.env.AUDIT_LO_DOCX ?? "";
const hasSoffice = (() => {
  try {
    execFileSync("soffice", ["--version"], { stdio: "pipe" });
    return true;
  } catch {
    return false;
  }
})();

function sofficeText(docx: string): string {
  const out = fs.mkdtempSync(path.join(os.tmpdir(), "lo-out-"));
  const loProfile = fs.mkdtempSync(path.join(os.tmpdir(), "lo-prof-"));
  execFileSync("soffice", [`-env:UserInstallation=file://${loProfile}`, "--headless", "--convert-to", "txt:Text (encoded):UTF8", "--outdir", out, docx], { stdio: "pipe", timeout: 120000 });
  const txt = path.join(out, path.basename(docx).replace(/\.docx$/, ".txt"));
  if (!fs.existsSync(txt)) throw new Error("LibreOffice could not open/convert " + docx);
  return fs.readFileSync(txt, "utf8");
}

/** Mark every word OUTSIDE inline tags with a sentinel so untranslated text is detectable. */
function fakeTranslate(segmentText: string): string {
  return segmentText
    .split(/(<[^>]+>)/)
    .map((part) => (part.startsWith("<") ? part : part.replace(/\p{L}[\p{L}\p{M}'’-]*/gu, (w) => `Ж${w}`)))
    .join("");
}

const countTags = (xml: string, tags: string[]) => Object.fromEntries(tags.map((t) => [t, xml.split(`<${t}`).length - 1]));
const STRUCT = ["w:hyperlink", "w:fldChar", "w:instrText", "w:bookmarkStart", "w:bookmarkEnd", "w:ins ", "w:del ", "w:footnoteReference", "w:endnoteReference", "w:commentRangeStart", "w:commentRangeEnd", "w:sdt>", "w:tbl>", "w:drawing"];

function partXml(docx: string, part: string): string {
  return strFromU8(unzipSync(fs.readFileSync(docx))[part]);
}

function roundTrip(src: string) {
  const dir = project({ "doc/source.docx": fs.readFileSync(src) });
  init(dir, ["de"]);
  const adapter = new DocxDocumentAdapter();
  const extracted = adapter.extract(path.join(dir, "doc/source.docx"));
  return { dir, adapter, extracted };
}

function realCorpusSuite(label: string, file: string) {
  describe.skipIf(!file || !fs.existsSync(file) || !hasSoffice)(`P-${label}. DOCX real-world corpus: ${label}`, () => {
    it(`P-${label}-1 unchanged round trip is byte-identical`, () => {
      const { dir, extracted } = roundTrip(file);
      const res = applyDocumentTranslations(dir, {
        sourceFile: "doc/source.docx",
        targetFile: "doc/same.docx",
        targetLocale: "de",
        updates: extracted.segments.map((s) => ({ id: s.id, text: s.text })),
      });
      expect(res.ok).toBe(true);
      expect(Buffer.compare(fs.readFileSync(path.join(dir, "doc/source.docx")), fs.readFileSync(path.join(dir, "doc/same.docx")))).toBe(0);
    });

    it(`P-${label}-2 extraction covers all visible text LibreOffice sees`, () => {
      const { dir, extracted } = roundTrip(file);
      const lo = sofficeText(path.join(dir, "doc/source.docx"));
      const segWords = new Set(extracted.segments.flatMap((s) => s.plainText.match(/\p{L}{3,}/gu) ?? []));
      const loWords = [...new Set(lo.match(/\p{L}{3,}/gu) ?? [])];
      const missing = loWords.filter((w) => !segWords.has(w));
      const lines = lo.split(/\r?\n/).filter((l) => missing.some((m) => l.includes(m))).map((l) => l.trim());
      console.log(`[P-${label}-2] segments=${extracted.segments.length} parts=${extracted.stats.parts.join(",")} words LibreOffice shows that no segment contains (${missing.length}): ${JSON.stringify(missing.slice(0, 30))}\n   in lines: ${JSON.stringify(lines.slice(0, 8))}`);
      expect(missing).toEqual([]);
    });

    it(`P-${label}-3 translated round trip: opens in LibreOffice, no source text left, structure preserved`, () => {
      const { dir, extracted } = roundTrip(file);
      const res = applyDocumentTranslations(dir, {
        sourceFile: "doc/source.docx",
        targetFile: "doc/de.docx",
        targetLocale: "de",
        updates: extracted.segments.map((s) => ({ id: s.id, text: fakeTranslate(s.text) })),
      });
      console.log(`[P-${label}-3] apply ok=${res.ok} updated=${res.segmentsUpdated}/${res.segmentsTotal} errors=${JSON.stringify(res.errors.slice(0, 3))}`);
      expect(res.ok).toBe(true);
      const out = path.join(dir, "doc/de.docx");
      const lo = sofficeText(out); // throws if LibreOffice cannot open it
      const leftovers = lo
        .split(/\r?\n/)
        .flatMap((l) => l.match(/\p{L}{3,}/gu) ?? [])
        .filter((w) => !w.startsWith("Ж"));
      console.log(`[P-${label}-3] untranslated words visible in output (${leftovers.length}): ${JSON.stringify([...new Set(leftovers)].slice(0, 25))}`);
      const before = countTags(partXml(path.join(dir, "doc/source.docx"), "word/document.xml"), STRUCT);
      const after = countTags(partXml(out, "word/document.xml"), STRUCT);
      expect(after).toEqual(before);
      expect(leftovers).toEqual([]);
    });
  });
}

realCorpusSuite("REF", REF);
realCorpusSuite("LO", LO);

/* ----------------------- Hand-written Word constructs ----------------------- */
const W = 'xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"';
function buildDocx(body: string, extra: Record<string, string> = {}): Uint8Array {
  return zipSync({
    "[Content_Types].xml": strToU8(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>`),
    "_rels/.rels": strToU8(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>`),
    "word/document.xml": strToU8(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:document ${W}><w:body>${body}</w:body></w:document>`),
    ...Object.fromEntries(Object.entries(extra).map(([k, v]) => [k, strToU8(v)])),
  });
}
const r = (t: string, rpr = "") => `<w:r>${rpr ? `<w:rPr>${rpr}</w:rPr>` : ""}<w:t xml:space="preserve">${t}</w:t></w:r>`;

function docProject(body: string) {
  const dir = project({ "d.docx": buildDocx(body) });
  init(dir, ["de"]);
  const ex = new DocxDocumentAdapter().extract(path.join(dir, "d.docx"));
  return { dir, ex, plain: ex.segments.map((s) => s.plainText).join(" | ") };
}

describe("Q. DOCX Word-specific constructs (hand-written OOXML)", () => {
  it("Q1 text inside an inline content control (w:sdt) is extracted", () => {
    const { plain } = docProject(`<w:p>${r("Customer: ")}<w:sdt><w:sdtPr><w:alias w:val="Name"/></w:sdtPr><w:sdtContent>${r("Enter the customer name")}</w:sdtContent></w:sdt></w:p>`);
    expect(plain).toContain("Enter the customer name");
  });

  it("Q2 text inside w:smartTag / w:customXml is extracted", () => {
    const { plain } = docProject(`<w:p>${r("Meet us in ")}<w:smartTag w:uri="urn:schemas-microsoft-com:office:smarttags" w:element="City">${r("Springfield")}</w:smartTag>${r(" next week.")}</w:p>`);
    expect(plain).toContain("Springfield");
  });

  it("Q3 the display text of a HYPERLINK complex field is translatable", () => {
    const body = `<w:p>${r("Read the ")}<w:r><w:fldChar w:fldCharType="begin"/></w:r><w:r><w:instrText xml:space="preserve"> HYPERLINK "https://example.com" </w:instrText></w:r><w:r><w:fldChar w:fldCharType="separate"/></w:r>${r("privacy policy")}<w:r><w:fldChar w:fldCharType="end"/></w:r>${r(" before signing up.")}</w:p>`;
    const { plain } = docProject(body);
    expect(plain).toContain("privacy policy");
  });

  it("Q4 text inside a tracked insertion (w:ins) is translated, not left in the source language", () => {
    const { plain } = docProject(`<w:p>${r("The committee ")}<w:ins w:id="1" w:author="A" w:date="2026-01-01T00:00:00Z">${r("formally ")}</w:ins>${r("approved the budget.")}</w:p>`);
    expect(plain).toContain("formally");
  });

  it("Q5 a comment range around one word keeps anchoring that word after translation", () => {
    const body = `<w:p>${r("Our ")}<w:commentRangeStart w:id="0"/>${r("primary")}<w:commentRangeEnd w:id="0"/><w:r><w:commentReference w:id="0"/></w:r>${r(" goal is zero incidents.")}</w:p>`;
    const { dir, ex } = docProject(body);
    const seg = ex.segments[0];
    console.log(`[Q5] segment: ${seg.text}`);
    // Translator moves words but keeps all tags (valid per the tag contract)
    const translated = seg.text.replace("Our primary", "Unser vorrangiges").replace(" goal is zero incidents.", " Ziel sind null Vorfälle.");
    const res = applyDocumentTranslations(dir, { sourceFile: "d.docx", targetFile: "de.docx", targetLocale: "de", updates: [{ id: seg.id, text: translated }] });
    expect(res.ok).toBe(true);
    const xml = partXml(path.join(dir, "de.docx"), "word/document.xml");
    const between = xml.split('<w:commentRangeStart w:id="0"/>')[1].split('<w:commentRangeEnd w:id="0"/>')[0];
    console.log(`[Q5] XML between comment range markers: ${between}`);
    expect(between).toMatch(/vorrangiges/);
  });

  it("Q6 a bookmark (cross-reference target) mid-sentence still wraps text after translation", () => {
    const body = `<w:p>${r("See ")}<w:bookmarkStart w:id="0" w:name="_Ref1"/>${r("Table 3")}<w:bookmarkEnd w:id="0"/>${r(" for details.")}</w:p>`;
    const { dir, ex } = docProject(body);
    const seg = ex.segments[0];
    const res = applyDocumentTranslations(dir, { sourceFile: "d.docx", targetFile: "de.docx", targetLocale: "de", updates: [{ id: seg.id, text: "Siehe Tabelle 3 für Details." }] });
    const xml = partXml(path.join(dir, "de.docx"), "word/document.xml");
    const between = xml.split('w:name="_Ref1"/>')[1].split("<w:bookmarkEnd")[0];
    console.log(`[Q6] ok=${res.ok} XML inside bookmark: ${between}`);
    expect(between).toMatch(/Tabelle/);
  });

  it("Q7 reordering formatted spans (<g> order swapped) is reflected in output order", () => {
    const body = `<w:p>${r("Click ", "<w:b/>")}${r("here", "<w:i/>")}</w:p>`;
    const { dir, ex } = docProject(body);
    const seg = ex.segments[0];
    console.log(`[Q7] segment: ${seg.text}`);
    // German puts the verb last: "<g2>Hier</g2> <g1>klicken</g1>"
    const ids = [...seg.text.matchAll(/<g id="(\d+)"/g)].map((m) => m[1]);
    const translated = `<g id="${ids[1]}" type="format">Hier</g><g id="${ids[0]}" type="format"> klicken</g>`;
    const res = applyDocumentTranslations(dir, { sourceFile: "d.docx", targetFile: "de.docx", targetLocale: "de", updates: [{ id: seg.id, text: translated }] });
    const xml = partXml(path.join(dir, "de.docx"), "word/document.xml");
    const text = [...xml.matchAll(/<w:t[^>]*>([^<]*)<\/w:t>/g)].map((m) => m[1]).join("");
    console.log(`[Q7] ok=${res.ok} output text: "${text}"`);
    expect(text).toBe("Hier klicken");
  });

  it("Q8 text the translator places OUTSIDE <g> tags is not silently dropped", () => {
    const body = `<w:p>${r("Save", "<w:b/>")}${r(" your work", "<w:i/>")}</w:p>`;
    const { dir, ex } = docProject(body);
    const seg = ex.segments[0];
    const ids = [...seg.text.matchAll(/<g id="(\d+)"/g)].map((m) => m[1]);
    const translated = `Bitte <g id="${ids[0]}" type="format">speichern</g><g id="${ids[1]}" type="format"> Sie Ihre Arbeit</g>`;
    const res = applyDocumentTranslations(dir, { sourceFile: "d.docx", targetFile: "de.docx", targetLocale: "de", updates: [{ id: seg.id, text: translated }] });
    const xml = partXml(path.join(dir, "de.docx"), "word/document.xml");
    console.log(`[Q8] ok=${res.ok}`);
    expect(res.ok === false || xml.includes("Bitte")).toBe(true);
  });

  it("Q9 translated text containing XML-invalid control characters is rejected or sanitised", () => {
    const { dir, ex } = docProject(`<w:p>${r("Hello world")}</w:p>`);
    applyDocumentTranslations(dir, { sourceFile: "d.docx", targetFile: "de.docx", targetLocale: "de", updates: [{ id: ex.segments[0].id, text: "Hallo\u0001Welt" }] });
    const xml = partXml(path.join(dir, "de.docx"), "word/document.xml");
    expect(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/.test(xml)).toBe(false);
  });

  it("Q10 literal '&#65;' typed in the document is not decoded into 'A'", () => {
    const { plain } = docProject(`<w:p>${r("Use &amp;#65; in HTML")}</w:p>`);
    expect(plain).toContain("&#65;");
  });

  it("Q11 text box content duplicated in mc:Choice and mc:Fallback is extracted once or linked", () => {
    const tb = (t: string) => `<w:txbxContent><w:p>${r(t)}</w:p></w:txbxContent>`;
    const body = `<w:p><w:r><mc:AlternateContent xmlns:mc="http://schemas.openxmlformats.org/markup-compatibility/2006"><mc:Choice Requires="wps"><w:drawing><wps:txbx xmlns:wps="x">${tb("Important notice")}</wps:txbx></w:drawing></mc:Choice><mc:Fallback><w:pict><v:textbox xmlns:v="urn:schemas-microsoft-com:vml">${tb("Important notice")}</v:textbox></w:pict></mc:Fallback></mc:AlternateContent></w:r></w:p>`;
    const { ex } = docProject(body);
    const n = ex.segments.filter((s) => s.plainText === "Important notice").length;
    console.log(`[Q11] "Important notice" segments: ${n}`);
    expect(n).toBe(1);
  });
});

describe("R. DOCX workflow", () => {
  it("R1 applying a long document in two batches keeps the first batch's translations", () => {
    const paras = Array.from({ length: 40 }, (_, i) => `<w:p>${r(`Paragraph number ${i + 1} of the handbook.`)}</w:p>`).join("");
    const dir = project({ "h.docx": buildDocx(paras) });
    init(dir, ["de"]);
    const page1 = prepareDocument(dir, { documentPath: "h.docx", targetLocale: "de", offset: 0 });
    const page2 = prepareDocument(dir, { documentPath: "h.docx", targetLocale: "de", offset: page1.segments.length });
    const tr = (segs: any[]) => segs.map((s) => ({ id: s.id, text: s.source.replace("Paragraph number", "Absatz Nummer") }));
    applyDocumentTranslations(dir, { sourceFile: "h.docx", targetFile: "h.de.docx", targetLocale: "de", updates: tr(page1.segments) });
    applyDocumentTranslations(dir, { sourceFile: "h.docx", targetFile: "h.de.docx", targetLocale: "de", updates: tr(page2.segments) });
    const xml = partXml(path.join(dir, "h.de.docx"), "word/document.xml");
    const translated = (xml.match(/Absatz Nummer/g) ?? []).length;
    console.log(`[R1] page sizes ${page1.segments.length}+${page2.segments.length}; translated paragraphs in final file: ${translated}/40`);
    expect(translated).toBe(40);
  });

  it("R2 targetFile equal to the source document is refused (would overwrite the original)", () => {
    const dir = project({ "a.docx": buildDocx(`<w:p>${r("Hello world")}</w:p>`) });
    init(dir, ["de"]);
    const seg = new DocxDocumentAdapter().extract(path.join(dir, "a.docx")).segments[0];
    const res = applyDocumentTranslations(dir, { sourceFile: "a.docx", targetFile: "a.docx", targetLocale: "de", updates: [{ id: seg.id, text: "Hallo Welt" }] });
    expect(res.ok).toBe(false);
  });

  it("R3 prepareDocument output stays compact for a large document (fullDocumentContext not repeated per page)", () => {
    const paras = Array.from({ length: 600 }, (_, i) => `<w:p>${r(`This is a fairly ordinary sentence in paragraph ${i} of a long policy manual.`)}</w:p>`).join("");
    const dir = project({ "big.docx": buildDocx(paras) });
    init(dir, ["de"]);
    const page = prepareDocument(dir, { documentPath: "big.docx", targetLocale: "de", limit: 10 });
    const size = JSON.stringify(page).length;
    console.log(`[R3] one 10-segment page of prepare = ${size} chars`);
    expect(size).toBeLessThan(20000);
  });

  it("R4 a zip bomb (tiny file, huge entry) is rejected without exhausting memory", () => {
    const huge = new Uint8Array(300 * 1024 * 1024); // 300 MB of zeros, compresses to ~300 KB
    const bomb = zipSync({ "word/document.xml": huge, "[Content_Types].xml": strToU8("<Types/>") }, { level: 9 });
    const dir = project({ "bomb.docx": bomb });
    init(dir, ["de"]);
    const before = process.memoryUsage().rss;
    let threw = false;
    try {
      new DocxDocumentAdapter().extract(path.join(dir, "bomb.docx"));
    } catch {
      threw = true;
    }
    const grewMb = (process.memoryUsage().rss - before) / 1024 / 1024;
    console.log(`[R4] compressed=${(bomb.length / 1024).toFixed(0)}KB threw=${threw} rss growth≈${grewMb.toFixed(0)}MB`);
    expect(threw).toBe(true);
  });
});
